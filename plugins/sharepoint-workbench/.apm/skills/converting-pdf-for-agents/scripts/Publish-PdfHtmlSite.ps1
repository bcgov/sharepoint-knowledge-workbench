<#
.SYNOPSIS
Publishes a static BC Design System HTML site (generated by convert_pdf.py publish)
to SharePoint Online using PnP.PowerShell and a workbench .psd1 config.

.DESCRIPTION
Reads publish-plan.json from -SiteRoot (produced by `convert_pdf.py publish`),
resolves the target SharePoint Online site from -ConfigPath (e.g. config-spo-dev.psd1)
or explicit -SiteUrl/-ClientId/-TenantId parameters, and uploads every planned HTML page
(to SitePages) and asset (to SiteAssets) in a single PnP.PowerShell session.

Handles SharePoint checkout/major check-in discipline (Set-PnPFileCheckedOut /
Set-PnPFileCheckedIn -CheckinType MajorCheckIn) so uploaded SitePages files are
published and visible to all users. After upload, writes online.json in the format
expected by `convert_pdf.py verify`.

By default performs zero SharePoint tenant I/O (dry-run plan only).
Live writes require -Execute -ConfirmToken PUBLISH-PDF-HTML-SITE.

.PARAMETER SiteRoot
Path to the local mirror folder containing publish-plan.json (created by `convert_pdf.py publish`).

.PARAMETER ConfigPath
Path to a workbench .psd1 configuration file (for example config-spo-dev.psd1).
Resolved via Get-WorkbenchConnectionConfig.ps1 if omitted.

.PARAMETER SiteUrl
Overrides Connection.SiteUrl from ConfigPath.

.PARAMETER ClientId
Overrides Connection.ClientId from ConfigPath.

.PARAMETER TenantId
Overrides Connection.TenantId from ConfigPath.

.PARAMETER TenantAdminUrl
Overrides Authentication.TenantAdminUrl from ConfigPath.

.PARAMETER CheckinComment
Comment used when checking in uploaded files as major versions.

.PARAMETER Overwrite
Allows replacing existing files on SharePoint (checks out existing files before uploading).
Without -Overwrite, existing files with matching byte size are skipped and size mismatches fail.

.PARAMETER OnlineOutputPath
Path where the live folder listing JSON (for `convert_pdf.py verify --online`) is written.
Defaults to <SiteRoot>\online.json.

.PARAMETER Execute
Executes live PnP.PowerShell uploads and check-ins. Omit for dry-run only.

.PARAMETER ConfirmToken
Required with -Execute. Must be PUBLISH-PDF-HTML-SITE.

.EXAMPLE
pwsh -File scripts/Publish-PdfHtmlSite.ps1 -SiteRoot temp/ceis/sp -ConfigPath C:\Users\RICHFREM\source\repos\CSB-Intranet\config-spo-dev.psd1

.EXAMPLE
pwsh -File scripts/Publish-PdfHtmlSite.ps1 -SiteRoot temp/ceis/sp -ConfigPath C:\Users\RICHFREM\source\repos\CSB-Intranet\config-spo-dev.psd1 -Overwrite -Execute -ConfirmToken PUBLISH-PDF-HTML-SITE
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$SiteRoot,

    [string]$ConfigPath,

    [string]$SiteUrl,

    [string]$ClientId,

    [string]$TenantId,

    [string]$TenantAdminUrl,

    [string]$CheckinComment = "Published via converting-pdf-for-agents",

    [switch]$Overwrite,

    [string]$OnlineOutputPath,

    [switch]$Execute,

    [string]$ConfirmToken
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

. (Join-Path $PSScriptRoot "Get-WorkbenchConnectionConfig.ps1")

$connectionConfig = if ($ConfigPath) {
    Get-WorkbenchConnectionConfig -Path $ConfigPath
} else {
    Get-WorkbenchConnectionConfig
}

if (-not $SiteUrl) { $SiteUrl = $connectionConfig.SiteUrl }
if (-not $ClientId) { $ClientId = $connectionConfig.ClientId }
if (-not $TenantId) { $TenantId = $connectionConfig.TenantId }
if (-not $TenantAdminUrl) { $TenantAdminUrl = $connectionConfig.TenantAdminUrl }

if (-not $SiteUrl -or -not $ClientId -or -not $TenantId) {
    throw "SiteUrl/ClientId/TenantId not resolved. Provide -ConfigPath (e.g. config-spo-dev.psd1) or -SiteUrl/-ClientId/-TenantId."
}

if (-not (Test-Path -LiteralPath $SiteRoot)) {
    throw "SiteRoot '$SiteRoot' does not exist."
}
$resolvedSiteRoot = (Resolve-Path -LiteralPath $SiteRoot).Path
$planPath = Join-Path $resolvedSiteRoot "publish-plan.json"
if (-not (Test-Path -LiteralPath $planPath)) {
    throw "publish-plan.json not found at '$planPath'. Run 'convert_pdf.py publish' first."
}

$plan = Get-Content -LiteralPath $planPath -Raw -Encoding utf8 | ConvertFrom-Json
if ($plan.status -ne "PASS") {
    throw "publish-plan.json status is '$($plan.status)' (expected 'PASS'). Fix link-check errors before publishing."
}
if (-not $plan.upload -or $plan.upload.Count -eq 0) {
    throw "publish-plan.json has no files in 'upload'."
}

foreach ($entry in $plan.upload) {
    $localFile = Join-Path $resolvedSiteRoot $entry.local
    if (-not (Test-Path -LiteralPath $localFile)) {
        throw "Planned local file missing: '$localFile'"
    }
}

if (-not $OnlineOutputPath) {
    $OnlineOutputPath = Join-Path $resolvedSiteRoot "online.json"
}

$siteServerRelativePath = ([System.Uri]$SiteUrl).AbsolutePath.TrimEnd('/')
$pagesCount = @($plan.upload | Where-Object { $_.library -eq "SitePages" }).Count
$assetsCount = @($plan.upload | Where-Object { $_.library -ne "SitePages" }).Count

if (-not $Execute) {
    Write-Host "`n[DRY RUN] Planned SharePoint static HTML site publication:" -ForegroundColor Yellow
    Write-Host "  SiteRoot          : $resolvedSiteRoot"
    Write-Host "  ConfigPath        : $(if ($connectionConfig.ConfigPath) { $connectionConfig.ConfigPath } else { '<explicit args>' })"
    Write-Host "  Target Site       : $SiteUrl"
    Write-Host "  Pages Path        : $($plan.pages_path) ($pagesCount file(s))"
    Write-Host "  Assets Path       : $($plan.assets_path) ($assetsCount file(s))"
    Write-Host "  Design System     : $(if ($plan.design_system) { $plan.design_system } else { '<embedded CSS>' })"
    Write-Host "  Overwrite         : $([bool]$Overwrite)"
    Write-Host "  Total Upload Files: $($plan.upload.Count)"
    Write-Host "`n  Sample actions:"
    $plan.upload | Select-Object -First 8 | ForEach-Object {
        $folderRel = if ($_.folder) { "$($_.library)/$($_.folder)" } else { $_.library }
        Write-Host "    - $($_.local) -> $folderRel/$($_.file)"
    }
    if ($plan.upload.Count -gt 8) {
        Write-Host "    ... and $($plan.upload.Count - 8) more file(s)."
    }
    Write-Host "`nTo execute live publication, re-run with: -Execute -ConfirmToken PUBLISH-PDF-HTML-SITE" -ForegroundColor Cyan

    return [PSCustomObject]@{
        DryRun       = $true
        SiteRoot     = $resolvedSiteRoot
        ConfigPath   = $connectionConfig.ConfigPath
        SiteUrl      = $SiteUrl
        PagesPath    = $plan.pages_path
        AssetsPath   = $plan.assets_path
        PlannedFiles = $plan.upload.Count
        Status       = "PLANNED"
    }
}

if ($ConfirmToken -ne "PUBLISH-PDF-HTML-SITE") {
    throw "-Execute requires -ConfirmToken PUBLISH-PDF-HTML-SITE."
}

$requiredCommands = @("Connect-PnPOnline", "Disconnect-PnPOnline", "Resolve-PnPFolder", "Get-PnPFile", "Add-PnPFile", "Set-PnPFileCheckedOut", "Set-PnPFileCheckedIn", "Get-PnPFolderItem")
$missingCommands = @($requiredCommands | Where-Object { -not (Get-Command $_ -ErrorAction SilentlyContinue) })
if ($missingCommands.Count -gt 0) {
    throw "PnP.PowerShell commands are required before execution: $($missingCommands -join ', '). Install/import PnP.PowerShell before executing."
}

$connectParameters = @{
    Url      = $SiteUrl
    ClientId = $ClientId
    Tenant   = $TenantId
}
if ($connectionConfig.AuthenticationMode -eq "Certificate" -and $connectionConfig.CertificateThumbprint) {
    $connectParameters["Thumbprint"] = $connectionConfig.CertificateThumbprint
} elseif ($connectionConfig.AuthenticationMode -eq "Certificate" -and $connectionConfig.CertificatePath) {
    $connectParameters["CertificatePath"] = $connectionConfig.CertificatePath
} else {
    $connectParameters["Interactive"] = $true
}
if ($TenantAdminUrl) { $connectParameters["TenantAdminUrl"] = $TenantAdminUrl }

Write-Host "Connecting to $SiteUrl..." -ForegroundColor Cyan
Connect-PnPOnline @connectParameters

$resolvedFolders = @{}
$uploadedCount = 0
$skippedCount = 0

try {
    foreach ($entry in $plan.upload) {
        $folderRel = if ($entry.folder) { "$($entry.library)/$($entry.folder)" } else { $entry.library }
        $folderRel = $folderRel.Trim('/')

        if (-not $resolvedFolders.ContainsKey($folderRel)) {
            Write-Host "Ensuring folder '$folderRel'..." -ForegroundColor Gray
            Resolve-PnPFolder -SiteRelativePath $folderRel -ErrorAction Stop | Out-Null
            $resolvedFolders[$folderRel] = $true
        }

        $localFile = Join-Path $resolvedSiteRoot $entry.local
        $localSize = (Get-Item -LiteralPath $localFile).Length
        $targetSiteRelativeUrl = "$folderRel/$($entry.file)"
        $targetServerRelativeUrl = if ($siteServerRelativePath) { "$siteServerRelativePath/$targetSiteRelativeUrl" } else { "/$targetSiteRelativeUrl" }

        $existingItem = Get-PnPFile -Url $targetServerRelativeUrl -AsListItem -ErrorAction SilentlyContinue
        if ($existingItem) {
            $remoteSize = [int64]$existingItem["File_x0020_Size"]
            if (-not $Overwrite) {
                if ($remoteSize -eq $localSize) {
                    $skippedCount++
                    continue
                }
                throw "Target file '$targetSiteRelativeUrl' already exists with different size (remote=$remoteSize, local=$localSize). Re-run with -Overwrite to replace."
            }
            try {
                Set-PnPFileCheckedOut -Url $targetServerRelativeUrl -ErrorAction Stop
            } catch {
                Write-Host "Checkout note for '$targetSiteRelativeUrl': $($_.Exception.Message)" -ForegroundColor Gray
            }
        }

        Add-PnPFile -Path $localFile -Folder $folderRel -NewFileName $entry.file -ErrorAction Stop | Out-Null
        $uploadedCount++

        $item = Get-PnPFile -Url $targetServerRelativeUrl -AsListItem -ErrorAction Stop
        $version = [string]$item["_UIVersionString"]
        if ($version -notmatch '^\d+\.0$') {
            Set-PnPFileCheckedIn -Url $targetServerRelativeUrl -CheckinType MajorCheckIn -Comment $CheckinComment -ErrorAction Stop
            $item = Get-PnPFile -Url $targetServerRelativeUrl -AsListItem -ErrorAction Stop
            $version = [string]$item["_UIVersionString"]
            if ($version -notmatch '^\d+\.0$') {
                throw "Uploaded '$targetSiteRelativeUrl' but version is still '$version' after MajorCheckIn."
            }
        }
    }

    # Collect live folder listings into online.json for `convert_pdf.py verify`
    $foldersToInspect = New-Object System.Collections.Generic.HashSet[string]
    foreach ($entry in $plan.upload) {
        $f = if ($entry.folder) { "$($entry.library)/$($entry.folder)" } else { $entry.library }
        [void]$foldersToInspect.Add($f.Trim('/'))
    }
    foreach ($ref in @($plan.reference_only)) {
        if ($ref) {
            $refFolder = ($ref -replace '/[^/]+$', '').Trim('/')
            if ($refFolder) { [void]$foldersToInspect.Add($refFolder) }
        }
    }

    $onlineMap = @{}
    foreach ($folderKey in $foldersToInspect) {
        $items = Get-PnPFolderItem -FolderSiteRelativeUrl $folderKey -ItemType File -ErrorAction SilentlyContinue
        $rows = @()
        foreach ($f in @($items)) {
            if (-not $f) { continue }
            $fServerRel = if ($siteServerRelativePath) { "$siteServerRelativePath/$folderKey/$($f.Name)" } else { "/$folderKey/$($f.Name)" }
            $li = Get-PnPFile -Url $fServerRel -AsListItem -ErrorAction SilentlyContinue
            $ver = if ($li) { [string]$li["_UIVersionString"] } else { "" }
            $lvl = if ($f.CheckOutType -ne "None") {
                "checkout"
            } elseif ($ver -match '^\d+\.0$') {
                "published"
            } else {
                "draft"
            }
            $rows += [PSCustomObject]@{
                name  = $f.Name
                size  = [int64]$f.Length
                level = $lvl
            }
        }
        $onlineMap[$folderKey] = $rows
    }

    $onlineMap | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $OnlineOutputPath -Encoding utf8

    $indexUrl = "$($SiteUrl.TrimEnd('/'))/$($plan.pages_path.Trim('/'))/index.html"
    Write-Host "`nUpload complete: $uploadedCount uploaded, $skippedCount skipped (unchanged)." -ForegroundColor Green
    Write-Host "Online listing written to: $OnlineOutputPath" -ForegroundColor Cyan
    Write-Host "Direct Browser URL: $indexUrl" -ForegroundColor Yellow
    Write-Host "Next: run 'python scripts/convert_pdf.py verify `"$resolvedSiteRoot`" --online `"$OnlineOutputPath`"'" -ForegroundColor Cyan

    return [PSCustomObject]@{
        DryRun           = $false
        SiteUrl          = $SiteUrl
        PagesPath        = $plan.pages_path
        AssetsPath       = $plan.assets_path
        UploadedFiles    = $uploadedCount
        SkippedFiles     = $skippedCount
        OnlineOutputPath = $OnlineOutputPath
        IndexUrl         = $indexUrl
        Status           = "UPLOADED"
    }
}
finally {
    Disconnect-PnPOnline -ErrorAction SilentlyContinue
}
