"""Builds the example enrichment package from a small synthetic document and canned agent answers.

Purpose: show the full output layout (deterministic extraction, AI topic files, index, chapter and document summaries,
provenance metadata, visible AI notices) without calling a model. The wording of the canned answers is illustrative only.

Key Input Dependencies: decompose.py, navigation.py, provenance.py.

Key Functions Index:
    - build_example()
"""

import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import decompose  # noqa: E402
import navigation  # noqa: E402
import provenance  # noqa: E402

SOURCE = "example-manual.pdf"
TEXT = (
    "Leave requests must be filed before the leave starts.\n\n"
    "Managers approve or decline a request within five working days.\n\n"
    "| Leave type | Notice |\n| --- | --- |\n| Annual | 10 days |\n| Sick | As soon as possible |\n\n"
    "Unused annual leave carries over for one year.\n\n"
    "Expense claims are submitted with receipts attached.\n\n"
    "Claims over the travel limit need a director's signature.\n\n"
    "Reimbursement is paid in the next pay cycle.\n"
)
_P2, _P3 = TEXT.index("| Leave type"), TEXT.index("Expense claims")
PAGE_MAP = [{"page": 1, "start": 0, "end": _P2}, {"page": 2, "start": _P2, "end": _P3},
            {"page": 3, "start": _P3, "end": len(TEXT)}]
FIXED_TIME = "2026-01-01T00:00:00+00:00"


def build_example(out_dir: Path) -> Path:
    """Write the package under `out_dir` and return it. `raw/` is the authoritative extraction; `ai-navigation/` is AI."""
    out_dir = Path(out_dir)
    raw, nav = out_dir / "raw", out_dir / "ai-navigation"
    raw.mkdir(parents=True, exist_ok=True)
    (raw / "extracted.md").write_text(TEXT, encoding="utf-8")
    (raw / "extraction.json").write_text(json.dumps(
        provenance.deterministic_metadata(SOURCE, "example-source-sha256"), indent=2) + "\n", encoding="utf-8")
    (raw / "page_map.json").write_text(json.dumps({"pages": PAGE_MAP}, indent=2) + "\n", encoding="utf-8")

    decompose.record_consent(nav, approved=True, provider="host-agent (example)", scope="document", estimated_tokens=500)
    edges = decompose.block_edges(TEXT)
    leave_start, expense_start = 0, TEXT.index("Expense claims")
    request = decompose.build_requests(nav, TEXT, PAGE_MAP, [{"start": 0, "end": None}], source_document=SOURCE)[0]
    assert leave_start in edges and expense_start in edges
    decompose.apply_response(nav, request, {"topics": [
        {"start": leave_start, "title": "Leave requests and approval", "uncertain": False},
        {"start": expense_start, "title": "Expense claims", "uncertain": True}]}, model="example-model")
    decompose.write_topics(nav, TEXT, PAGE_MAP, source_document=SOURCE, extracted_content="../raw/extracted.md",
                           source_sha256="example-source-sha256")

    summaries = {
        "leave": {"summary": "Explains how to request leave, who approves it and how much notice each type needs.",
                  "keywords": ["leave", "approval", "notice"], "synonyms": ["vacation", "time off"]},
        "expense": {"summary": "Covers submitting expense claims, the signature rule and when payment arrives.",
                    "keywords": ["expenses", "reimbursement"], "synonyms": ["claims", "refund"]},
    }
    requests = navigation.build_summary_requests(nav, TEXT)
    for req, key in zip(requests, ("leave", "expense")):
        navigation.apply_summary_response(nav, req, summaries[key], model="example-model")
    roll = navigation.build_rollup_request(nav)
    files = [t["file"] for t in roll["topics"]]
    navigation.apply_rollup_response(nav, roll, {
        "document_summary": "A short staff guide to taking leave and claiming expenses.",
        "groups": [{"title": "Leave", "summary": "Rules for leave.", "topics": [files[0]]},
                   {"title": "Expenses", "summary": "Rules for expense claims.", "topics": [files[1]]}],
        "relations": [{"from": files[1], "to": files[0], "reason": "both depend on manager approval"}]},
        model="example-model")
    gen = decompose._read_json(nav / decompose.GENERATION_FILE)
    gen["generation_timestamp"] = FIXED_TIME
    decompose._write_json(nav / decompose.GENERATION_FILE, gen)
    navigation.write_navigation(nav, page_count=3, extracted_rel="../raw/extracted.md",
                                source_sha256="example-source-sha256")
    shutil.rmtree(nav / "requests", ignore_errors=True)
    (out_dir / "README.md").write_text(
        "# Example enrichment package\n\nGenerated by `scripts/enrichment/build_example.py` from a synthetic document "
        f"(`{SOURCE}` does not exist). `raw/` is the authoritative deterministic extraction. `ai-navigation/` holds "
        "AI-generated navigation aids (canned example wording): `index.md`, `chapters/`, `topics/`, `navigation.json`, "
        "`generation.json`. Every AI file carries the AI-GENERATED NAVIGATION AID notice and discovery-only metadata. `raw/extraction.json` holds the authoritative extraction metadata.\n",
        encoding="utf-8")
    return out_dir


if __name__ == "__main__":
    print(build_example(Path(sys.argv[1]) if len(sys.argv) > 1 else Path("enrichment-example")))
